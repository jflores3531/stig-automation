def test_supported_release(tmpdir):
    print('\nsupported release: `show version` answers the model and the release')
    known = report_for(tmpdir, 'release')
    line = verdict(known, 'V-220569')
    check('the release and the model are in the report, so no login is needed for them',
          '17.12.4' in line and 'C9300-48P' in line, line)
    # 17.12 is an Extended Maintenance release - every third minor - so it
    # passes on the numbering alone, with no table for anyone to re-read.
    check('an Extended Maintenance release passes',
          status(known, 'V-220569') == 'PASS', line)
    check('and the reason says which track it is on',
          'Extended Maintenance' in line, line)

    past_support = report_for(tmpdir, 'eos', version=SHOW_VERSION_3850)
    line = verdict(past_support, 'V-220569')
    check('hardware past its last date of support is a finding, whatever it runs',
          status(past_support, 'V-220569') == 'FAIL', line)
    check('and the reason gives the date rather than asserting it',
          '2025-10-31' in line, line)

    classic = report_for(tmpdir, 'vios', version=SHOW_VERSION_VIOS)
    line = verdict(classic, 'V-220569')
    check('classic IOS names its release and model on different lines, and both are read',
          '15.2(20170717:130322)' in line and 'vios_l2' in line, line)

    # The rule that used to need a hand-maintained list: 17.15 had never been
    # read off cisco.com, so it reported NOT AUTOMATED. It is every third minor,
    # so it is an EMR, so it passes - and 17.18 will the day it ships.
    newer = report_for(tmpdir, 'neweremr', version=SHOW_VERSION_UNKNOWN_RELEASE)
    line = verdict(newer, 'V-220569')
    check('an EMR nobody has written down anywhere still passes',
          status(newer, 'V-220569') == 'PASS', line)
    check('and names the release it decided that on', '17.15.1' in line, line)

    # The finding this rule now catches on its own. 17.13 is Standard
    # Maintenance: twelve months and no extension, whatever the config says.
    smr = report_for(tmpdir, 'smr', version=fixtures.SHOW_VERSION.replace(
        '17.12.04', '17.13.01').replace('Version 17.12.4', 'Version 17.13.1'))
    line = verdict(smr, 'V-220569')
    check('a Standard Maintenance release is a finding', status(smr, 'V-220569') == 'FAIL', line)
    check('and the reason says why and what to move to',
          '12 months' in line and '17.12' in line and '17.15' in line, line)

    # The switch table at the end of `show version` is the third place the
    # model and release appear, and on some images the only one. A switch whose
    # banner this does not recognise and which prints no `Model Number` line
    # used to report "could not read a model from `show version`" with the
    # model on screen in the SW Version table the whole time.
    table_only = report_for(tmpdir, 'tableonly', version=SHOW_VERSION_TABLE_ONLY)
    line = verdict(table_only, 'V-220569')
    check('the SW Version column answers the rule when nothing else does',
          '17.12.4' in line and 'C9300-48P' in line, line)
    check('and it is the same verdict the banner would have given',
          status(table_only, 'V-220569') == status(known, 'V-220569'), line)

    stacked = report_for(tmpdir, 'stacked', version=SHOW_VERSION_STACK)
    line = verdict(stacked, 'V-220569')
    check('a stack is read from its active member, not whichever row came first',
          '17.12.4' in line and '16.9.8' not in line, line)

    # The model has to come from the same member as the release. Reading it
    # from the first `Model Number` line instead would report the 3850 here,
    # whose last date of support has passed - a FAIL on a stack whose active
    # switch is a supported C9300.
    mixed = report_for(tmpdir, 'mixedstack', version=SHOW_VERSION_MIXED_STACK)
    line = verdict(mixed, 'V-220569')
    check('and its model comes from that same member, not the first one listed',
          'C9300-48P' in line and 'WS-C3850' not in line, line)
    check('so a mixed stack is not failed for hardware it is not running on',
          status(mixed, 'V-220569') == 'PASS', line)


def strip_service_policy(config, *ports):
    """The fixture config with `service-policy output` removed from `ports`,
    or from every port if none are named."""
    out, current = [], None
    for line in config.splitlines():
        interface = re.match(r'interface (\S+)', line)
        if interface:
            current = interface.group(1)
        if 'service-policy output' in line and (not ports or current in ports):
            continue
        out.append(line)
    return '\n'.join(out)


def test_qos_bandwidth(tmpdir):
    print('\nQoS: the MQC shape the IOS XE book asks for, read from config text')
    compliant = report_for(tmpdir, 'qos')
    line = verdict(compliant, 'V-220651')
    check('V-220651 passes on the shape the Check Content shows',
          status(compliant, 'V-220651') == 'PASS', line)
    check('and the reason names the traffic types it found bandwidth reserved for',
          all(t in line for t in ('C2_VOICE', 'VOICE', 'VIDEO', 'PREFERRED_DATA')), line)

    none = report_for(tmpdir, 'noqos',
                      running_config=strip_service_policy(fixtures.RUNNING_CONFIG))
    line = verdict(none, 'V-220651')
    check('no service-policy anywhere is "QoS is not enabled"',
          status(none, 'V-220651') == 'FAIL' and 'not enabled' in line, line)

    partial = report_for(tmpdir, 'partialqos', running_config=strip_service_policy(
        fixtures.RUNNING_CONFIG, 'GigabitEthernet1/0/1'))
    line = verdict(partial, 'V-220651')
    # A port left out used to fail this. The finding condition is one sentence
    # - "If quality of service (QoS) has not been enabled, this is a finding" -
    # and a switch running a valid policy on some of its ports has enabled QoS,
    # so failing it invented a finding DISA did not write. Reported instead,
    # the same way an uncovered traffic type is.
    check('a port left out of the policy does not fail the rule',
          status(partial, 'V-220651') == 'PASS', line)
    check('but it is named, like every other per-port rule here',
          'GigabitEthernet1/0/1' in line, line)
    check('and the reason says the port is unprotected rather than burying it',
          'floodable' in line and '2 of 3' in line, line)

    renamed = fixtures.RUNNING_CONFIG
    for stig_name, local in (('C2_VOICE', 'SITE-C2'), ('VOICE', 'SITE-VOICE'),
                             ('VIDEO', 'SITE-VIDEO'), ('PREFERRED_DATA', 'SITE-DATA')):
        renamed = re.sub(rf'\b{stig_name}\b', local, renamed)
    local_names = report_for(tmpdir, 'renamedqos', running_config=renamed)
    line = verdict(local_names, 'V-220651')
    check('the same policy under local class names still passes - DSCP decides, not spelling',
          status(local_names, 'V-220651') == 'PASS', line)

    marking_only = re.sub(r'^  (priority level \d+ \d+|bandwidth percent \d+)$',
                          '  set dscp af11', fixtures.RUNNING_CONFIG, flags=re.M)
    line = verdict(report_for(tmpdir, 'markingonly', running_config=marking_only), 'V-220651')
    check('a policy that only marks traffic reserves nothing, so it is a finding',
          'FAIL' in line and 'reserves bandwidth' in line, line)


APPLET_HEADER = 'event manager applet BACKUP_CONFIG'
COPY_ACTION = ('action 3 cli command "copy running-config '
               'scp://backup@192.0.2.40/configs/$_info_routername-running-config"')


def backup_config(**edits):
    """The fixture config with one thing about its backup applet changed."""
    cfg = fixtures.RUNNING_CONFIG
    if edits.get('no_applet'):
        return cfg.split(APPLET_HEADER)[0] + 'end'
    if edits.get('trigger'):
        cfg = cfg.replace('%SYS-5-CONFIG_I', edits['trigger'])
    if edits.get('no_copy'):
        cfg = cfg.replace(' ' + COPY_ACTION + '\n', '')
    if edits.get('scheme'):
        cfg = cfg.replace('scp://backup@', edits['scheme'] + '://backup@')
    if edits.get('password'):
        cfg = cfg.replace('scp://backup@', 'scp://backup:' + edits['password'] + '@')
    if edits.get('no_prompt_quiet'):
        cfg = cfg.replace('file prompt quiet\n', '')
    if edits.get('no_bypass'):
        cfg = cfg.replace(' authorization bypass\n', '')
    return cfg


def test_config_backup(tmpdir):
    """V-220566 was NOT AUTOMATED on the IOS book's version of the rule, whose
    check is an SCP server held by the site. The IOS XE book asks about the
    mechanism instead - an EEM applet on `%SYS-5-CONFIG_I` copying the running
    configuration somewhere secure - and that is running-config text.

    Its finding sentence names two conditions: no automated backup on change,
    or one taken "using an insecure method like a cleartext password". Those
    fail. The two supporting settings the Check Content also asks to verify are
    what make the applet run rather than findings DISA wrote, so they are
    reported on the PASS instead."""
    print('\nconfiguration backup on change: a rule the IOS XE book makes answerable')
    passing = report_for(tmpdir, 'backupok')
    line = verdict(passing, 'V-220566')
    check('the compliant switch passes rather than reporting NOT AUTOMATED',
          status(passing, 'V-220566') == 'PASS', line)
    check('and the reason says where it backs up to',
          'scp://backup@192.0.2.40' in line, line)

    none = verdict(report_for(tmpdir, 'noapplet',
                              running_config=backup_config(no_applet=True)), 'V-220566')
    check('no EEM applet at all is a finding',
          'FAIL' in none and 'event manager applet' in none, none)

    other = verdict(report_for(tmpdir, 'othertrigger',
                               running_config=backup_config(trigger='%LINK-3-UPDOWN')),
                    'V-220566')
    check('an applet that fires on something other than a config change is a finding',
          'FAIL' in other and '%SYS-5-CONFIG_I' in other, other)

    quiet = verdict(report_for(tmpdir, 'nocopy',
                               running_config=backup_config(no_copy=True)), 'V-220566')
    check('an applet that notices the change and copies nothing is a finding',
          'FAIL' in quiet and 'copying the running configuration' in quiet, quiet)

    # The second half of the finding sentence, in its two forms.
    clear = verdict(report_for(tmpdir, 'ftp',
                               running_config=backup_config(scheme='ftp')), 'V-220566')
    check('backing up over a cleartext transport is a finding',
          'FAIL' in clear and 'in the clear' in clear, clear)

    secret = verdict(report_for(tmpdir, 'password',
                                running_config=backup_config(password='hunter2')), 'V-220566')
    check('and so is a password in the destination - the Check Content reads its '
          'absence as key authentication',
          'FAIL' in secret and 'cleartext password' in secret, secret)

    # Asked for by the Check Content, but not named by the finding sentence:
    # reported on the PASS rather than invented as a finding.
    no_quiet = verdict(report_for(tmpdir, 'noquiet',
                                  running_config=backup_config(no_prompt_quiet=True)),
                       'V-220566')
    check('a missing `file prompt quiet` is said out loud, not failed',
          status(no_quiet, 'V-220566') == 'PASS' and 'file prompt quiet' in no_quiet, no_quiet)

    no_bypass = verdict(report_for(tmpdir, 'nobypass',
                                   running_config=backup_config(no_bypass=True)), 'V-220566')
    check('and so is a missing `authorization bypass`',
          status(no_bypass, 'V-220566') == 'PASS' and 'authorization bypass' in no_bypass,
          no_bypass)


if __name__ == '__main__':
    with tempfile.TemporaryDirectory() as tmp:
        test_persistent_logging(tmp)
        test_pki_trustpoint(tmp)
        test_supported_release(tmp)
        test_qos_bandwidth(tmp)
        test_config_backup(tmp)
    print('\n' + ('ALL CHECKS PASSED' if not failures
                  else f'{len(failures)} FAILED: {", ".join(failures)}'))
    sys.exit(1 if failures else 0)
