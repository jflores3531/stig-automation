#!/usr/bin/env python
"""The rules that used to end a report with "go and log into the switch".

Run directly: `python3 tests/test_manual_review_rules.py`. No framework, no
device. Driven through the CLI like the other audit suites - l2_stig_audit.py
parses argv at import, so a report is the only way to read its verdicts.

Every case here came off one hand-annotated IOS XE report:

  * V-220531/532/533 (persistent logging) reported PASS with a reason that
    said the rule was not applicable. Two different sentences on a checklist,
    and only one of them is true - `NOT_A_FINDING` claims the switch protects
    persistent log files it does not keep.

  * V-220567 (PKI) reported NOT AUTOMATED on every switch, because every
    switch has a trustpoint: `TP-self-signed-<serial>`, generated by IOS XE
    itself. Nothing there enrolled with a CA, so the review the rule asks for
    has no subject - confirmed on a real switch with `show running-config |
    include enrollment url`, which printed nothing. Where a switch IS enrolled,
    the URL that names the CA is in running-config too, and comparing its host
    against the approved list is the rule's whole review step - so that is
    answered here rather than handed back.

  * V-220569 (supported release) was NOT AUTOMATED with nothing to act on. It
    needs `show version`, which the audit is already connected to run.

  * V-220651 (QoS) was NOT AUTOMATED because the IOS book's `mls qos` cannot
    answer it. The IOS XE book asks for the MQC shape, which is config text.

V-220566 (configuration backups) stays NOT AUTOMATED: which server a switch
backs up to is a fact about the site, not about the switch, and no command
here can discover it.
"""

import os
import re
import subprocess
import sys
import tempfile

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, PROJECT)
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import capture
import fixtures

failures = []


def check(name, condition, detail=''):
    print(f'  {"ok  " if condition else "FAIL"} {name}')
    if not condition:
        if detail:
            print(f'       {detail}')
        failures.append(name)


def report_for(tmpdir, name, **overrides):
    """An IOS XE report for the fixture switch, with `show ...` outputs
    replaced by keyword: report_for(tmp, 'x', running_config=..., version=...)."""
    outputs = dict(fixtures.OUTPUTS)
    for key, command in (('running_config', 'show running-config'),
                         ('version', 'show version')):
        if key in overrides:
            outputs[command] = overrides[key]
    path = capture.write(os.path.join(tmpdir, name + '.capture'), outputs)
    result = subprocess.run(
        [sys.executable, os.path.join(PROJECT, 'l2_stig_audit.py'), 'TESTSW01',
         '--from-capture', path, '--non-user-vlans', '1,10,999,1000'],
        capture_output=True, text=True, cwd=PROJECT, timeout=120)
    return result.stdout + result.stderr


def verdict(report, rule_id):
    """The status line and its reason for one rule, as one string."""
    lines = report.splitlines()
    for i, line in enumerate(lines):
        if rule_id in line:
            return ' | '.join(part.strip() for part in lines[i:i + 2])
    return f'{rule_id} not in report'


def status(report, rule_id):
    line = verdict(report, rule_id).split('|')[0]
    for name in ('NOT APPLICABLE', 'NOT AUTOMATED', 'PASS', 'FAIL'):
        if name in line:
            return name
    return line.strip()


PERSISTENT = 'logging persistent url disk0:/logfile size 134217728 filesize 16384'
AUDIT_RULES = ('V-220531', 'V-220532', 'V-220533')


def test_persistent_logging(tmpdir):
    print('persistent logging: not enabled is not applicable, not a pass')
    off = report_for(tmpdir, 'nopersist')
    for rule in AUDIT_RULES:
        check(f'{rule} is NOT APPLICABLE with no `logging persistent`',
              status(off, rule) == 'NOT APPLICABLE', verdict(off, rule))

    on = report_for(tmpdir, 'persist', running_config=fixtures.RUNNING_CONFIG.replace(
        'logging buffered 64000', f'logging buffered 64000\n{PERSISTENT}'))
    for rule in AUDIT_RULES:
        check(f'{rule} passes once persistent logging is on and privilege is default 15',
              status(on, rule) == 'PASS', verdict(on, rule))
    check('and the reason says why an absent `file privilege` line is compliant',
          'default of privilege 15' in verdict(on, 'V-220531'), verdict(on, 'V-220531'))

    lowered = report_for(tmpdir, 'privilege10', running_config=fixtures.RUNNING_CONFIG.replace(
        'logging buffered 64000', f'logging buffered 64000\n{PERSISTENT}\nfile privilege 10'))
    for rule in AUDIT_RULES:
        check(f'{rule} fails on `file privilege 10`, which is the rule\'s finding',
              status(lowered, rule) == 'FAIL', verdict(lowered, rule))


def test_pki_trustpoint(tmpdir):
    print('\nPKI: a self-signed trustpoint is not a certificate from a provider')
    self_signed = report_for(tmpdir, 'selfsigned')
    check('V-220567 is NOT APPLICABLE against `TP-self-signed-...`',
          status(self_signed, 'V-220567') == 'NOT APPLICABLE', verdict(self_signed, 'V-220567'))
    check('and the reason names the trustpoint it decided that on',
          'TP-self-signed-1234567890' in verdict(self_signed, 'V-220567'),
          verdict(self_signed, 'V-220567'))

    none = report_for(tmpdir, 'notrustpoint', running_config=re.sub(
        r'crypto pki trustpoint.*?(?=banner login)', '', fixtures.RUNNING_CONFIG, flags=re.S))
    check('so is a switch with no trustpoint at all',
          status(none, 'V-220567') == 'NOT APPLICABLE', verdict(none, 'V-220567'))

    # The rule's own Check Content is "the CA trust point will contain the URL
    # of the CA ... verify this is a DOD or DOD-approved CA", and that URL is
    # in running-config - so the audit answers it rather than printing the URL
    # and asking someone to log in and read what it just read.
    enrolled = report_for(tmpdir, 'enrolled', running_config=fixtures.RUNNING_CONFIG.replace(
        ' enrollment selfsigned', ' enrollment url http://ca.example.mil'))
    check('a trustpoint enrolled with an approved CA passes',
          status(enrolled, 'V-220567') == 'PASS', verdict(enrolled, 'V-220567'))
    check('and the reason names the URL it decided that on',
          'http://ca.example.mil' in verdict(enrolled, 'V-220567'),
          verdict(enrolled, 'V-220567'))

    outside = report_for(tmpdir, 'unapprovedca', running_config=fixtures.RUNNING_CONFIG.replace(
        ' enrollment selfsigned', ' enrollment url http://ca.example.com'))
    check('a CA outside approved_ca_hosts is the finding, not a note',
          status(outside, 'V-220567') == 'FAIL', verdict(outside, 'V-220567'))
    check('and the reason says which host and which list',
          'ca.example.com' in verdict(outside, 'V-220567')
          and 'approved_ca_hosts' in verdict(outside, 'V-220567'),
          verdict(outside, 'V-220567'))

    # `enrollment terminal` is a real CA enrolment whose CA running-config
    # never names. That one stays NOT AUTOMATED - the honest verdict when the
    # evidence is not in the text - rather than being guessed either way.
    terminal = report_for(tmpdir, 'terminalenrol', running_config=fixtures.RUNNING_CONFIG.replace(
        ' enrollment selfsigned', ' enrollment terminal'))
    check('an enrolment with no URL in the config is still NOT AUTOMATED',
          status(terminal, 'V-220567') == 'NOT AUTOMATED', verdict(terminal, 'V-220567'))
    check('and names the command that answers it',
          'show crypto pki certificates' in verdict(terminal, 'V-220567'),
          verdict(terminal, 'V-220567'))


