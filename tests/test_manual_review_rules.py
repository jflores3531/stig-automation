def test_supported_release(tmpdir):
    print('\nsupported release: `show version` answers the model and the release')
    known = report_for(tmpdir, 'release')
    line = verdict(known, 'V-220569')
    check('the release and the model are in the report, so no login is needed for them',
          '17.12.4' in line and 'C9300-48P' in line, line)
    # PASS while SUPPORTED_RELEASES is current, NOT AUTOMATED once that reading
    # goes stale - never a bare NOT AUTOMATED with nothing to act on.
    check('a reviewed release passes, or says the list needs re-reading',
          status(known, 'V-220569') == 'PASS' or 'update SUPPORTED_RELEASES' in line, line)

    past_support = report_for(tmpdir, 'eos', version=SHOW_VERSION_3850)
    line = verdict(past_support, 'V-220569')
    check('hardware past its last date of support is a finding, whatever it runs',
          status(past_support, 'V-220569') == 'FAIL', line)
    check('and the reason gives the date rather than asserting it',
          '2025-10-31' in line, line)

    classic = report_for(tmpdir, 'vios', version=SHOW_VERSION_VIOS)
    line = verdict(classic, 'V-220569')
    check('classic IOS names its release and model on different lines, and both are read',
          '15.2(20170717:130322)' in line and 'vios_l2' in line, line)

    unknown = report_for(tmpdir, 'unknownrelease', version=SHOW_VERSION_UNKNOWN_RELEASE)
    line = verdict(unknown, 'V-220569')
    check('a release the table does not know is NOT AUTOMATED, not a finding',
          status(unknown, 'V-220569') == 'NOT AUTOMATED', line)
    check('and it says so in those words, with the release to look up',
          '17.15.1' in line and 'unknown, not unsupported' in line, line)

    # The switch table at the end of `show version` is the third place the
    # model and release appear, and on some images the only one. A switch whose
    # banner this does not recognise and which prints no `Model Number` line
    # used to report "could not read a model from `show version`" with the
    # model on screen in the SW Version table the whole time.
    table_only = report_for(tmpdir, 'tableonly', version=SHOW_VERSION_TABLE_ONLY)
    line = verdict(table_only, 'V-220569')
    check('the SW Version column answers the rule when nothing else does',
          '17.12.4' in line and 'C9300-48P' in line, line)
    check('and it is the same verdict the banner would have given',
          status(table_only, 'V-220569') == status(known, 'V-220569'), line)

    stacked = report_for(tmpdir, 'stacked', version=SHOW_VERSION_STACK)
    line = verdict(stacked, 'V-220569')
    check('a stack is read from its active member, not whichever row came first',
          '17.12.4' in line and '16.9.8' not in line, line)


def strip_service_policy(config, *ports):
    """The fixture config with `service-policy output` removed from `ports`,
    or from every port if none are named."""
    out, current = [], None
    for line in config.splitlines():
        interface = re.match(r'interface (\S+)', line)
        if interface:
            current = interface.group(1)
        if 'service-policy output' in line and (not ports or current in ports):
            continue
        out.append(line)
    return '\n'.join(out)


def test_qos_bandwidth(tmpdir):
    print('\nQoS: the MQC shape the IOS XE book asks for, read from config text')
    compliant = report_for(tmpdir, 'qos')
    line = verdict(compliant, 'V-220651')
    check('V-220651 passes on the shape the Check Content shows',
          status(compliant, 'V-220651') == 'PASS', line)
    check('and the reason names the traffic types it found bandwidth reserved for',
          all(t in line for t in ('C2_VOICE', 'VOICE', 'VIDEO', 'PREFERRED_DATA')), line)

    none = report_for(tmpdir, 'noqos',
                      running_config=strip_service_policy(fixtures.RUNNING_CONFIG))
    line = verdict(none, 'V-220651')
    check('no service-policy anywhere is "QoS is not enabled"',
          status(none, 'V-220651') == 'FAIL' and 'not enabled' in line, line)

    partial = report_for(tmpdir, 'partialqos', running_config=strip_service_policy(
        fixtures.RUNNING_CONFIG, 'GigabitEthernet1/0/1'))
    line = verdict(partial, 'V-220651')
    check('a port left out of the policy is a finding',
          status(partial, 'V-220651') == 'FAIL', line)
    check('and the port is named, like every other per-port rule here',
          'GigabitEthernet1/0/1' in line, line)

    renamed = fixtures.RUNNING_CONFIG
    for stig_name, local in (('C2_VOICE', 'SITE-C2'), ('VOICE', 'SITE-VOICE'),
                             ('VIDEO', 'SITE-VIDEO'), ('PREFERRED_DATA', 'SITE-DATA')):
        renamed = re.sub(rf'\b{stig_name}\b', local, renamed)
    local_names = report_for(tmpdir, 'renamedqos', running_config=renamed)
    line = verdict(local_names, 'V-220651')
    check('the same policy under local class names still passes - DSCP decides, not spelling',
          status(local_names, 'V-220651') == 'PASS', line)

    marking_only = re.sub(r'^  (priority level \d+ \d+|bandwidth percent \d+)$',
                          '  set dscp af11', fixtures.RUNNING_CONFIG, flags=re.M)
    line = verdict(report_for(tmpdir, 'markingonly', running_config=marking_only), 'V-220651')
    check('a policy that only marks traffic reserves nothing, so it is a finding',
          'FAIL' in line and 'reserves bandwidth' in line, line)


if __name__ == '__main__':
    with tempfile.TemporaryDirectory() as tmp:
        test_persistent_logging(tmp)
        test_pki_trustpoint(tmp)
        test_supported_release(tmp)
        test_qos_bandwidth(tmp)
