#!/usr/bin/env python
"""The rules that used to end a report with "go and log into the switch".

Run directly: `python3 tests/test_manual_review_rules.py`. No framework, no
device. Driven through the CLI like the other audit suites - l2_stig_audit.py
parses argv at import, so a report is the only way to read its verdicts.

Every case here came off one hand-annotated IOS XE report:

  * V-220531/532/533 (persistent logging) reported PASS with a reason that
    said the rule was not applicable. Two different sentences on a checklist,
    and only one of them is true - `NOT_A_FINDING` claims the switch protects
    persistent log files it does not keep.

  * V-220567 (PKI) reported NOT AUTOMATED on every switch, because every
    switch has a trustpoint: `TP-self-signed-<serial>`, generated by IOS XE
    itself. Nothing there enrolled with a CA, so the review the rule asks for
    has no subject - confirmed on a real switch with `show running-config |
    include enrollment url`, which printed nothing. An `enrollment url` is the
    only thing the rule is about, so a switch with none is NOT APPLICABLE and
    carries the justification a reviewer would otherwise type; where one IS
    present it names the CA, and comparing its host against the approved list
    is the rule's whole review step - answered here rather than handed back.

  * V-220569 (supported release) was NOT AUTOMATED with nothing to act on. It
    needs `show version`, which the audit is already connected to run - and on
    IOS XE the answer is in the numbering rather than in a lookup: every third
    minor (17.3, 17.6, 17.9, 17.12, 17.15) is an Extended Maintenance release
    with 36-48 months of support, everything between is Standard Maintenance
    with twelve. An SMR is a finding no configuration can fix.

  * V-220651 (QoS) was NOT AUTOMATED because the IOS book's `mls qos` cannot
    answer it. The IOS XE book asks for the MQC shape, which is config text.

  * V-220566 (configuration backups) was NOT AUTOMATED on the strength of the
    IOS book's version, whose check is an SCP server held by the site rather
    than by the switch. The IOS XE book asks about the mechanism instead - an
    EEM applet on `%SYS-5-CONFIG_I` copying the running configuration to a
    secure destination - which is config text like any other rule.
"""

